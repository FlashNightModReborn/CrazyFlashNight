"""CF6 K3 batch executor. Requires the Astra-owned converter-ready.json; never runs CS6.

Fail-closed: ready_contract validates schema/status, the pinned files array
(path/sha256/bytes, unique, on-disk match, equal to the actual import closure),
the pinned map-input and every job against live bytes before anything runs.
The locked plan.json is cross-checked against the signal and live inputs; a
stale plan refuses execution instead of becoming truth. Dependencies, the
signal and consumed inputs (map-input + the target source SVG) are re-hashed
before and after every target; any mutation fails the target and aborts the
batch so identities never mix. Reuse requires complete source snapshots, the
native manifest with original texture byte digests verified in batch/assets,
and for zero-texture targets the assembled XFL closure; a failed or partial
product is never 'reused' because files merely exist. Every target records its
real exit code; failures keep evidence and independent targets continue.
Targets whose locked plan entry carries a builder field (the reviewed
floor_lattice vector-pattern wrapper) are generated by that builder instead of
plain build-layer.py; the same pre/post verification and closure audit apply.
"""
from pathlib import Path
import argparse
import datetime
import hashlib
import json
import subprocess
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import ready_contract

HERE = Path(__file__).resolve().parent
NV = HERE.parent
RUNTIME = NV.parent
ROOT = RUNTIME.parents[1]
PLAN = HERE / 'plan.json'
SIGNAL = HERE / 'converter-ready.json'
LOGS = HERE / 'logs'
ASSET_ROOTS = [(NV / 'assets').resolve(), (HERE / 'assets').resolve()]
MAP_INPUT_REL = ready_contract.MAP_INPUT.relative_to(ROOT).as_posix()


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def reusable(layer_dir, name, job, map_input_sha, expect_textures):
    report = layer_dir / 'report.json'
    manifest = layer_dir / 'texture-manifest.json'
    conv = layer_dir / 'converter.source.py'
    build = layer_dir / 'builder.source.py'
    recipe = layer_dir / 'import-textures.jsfl'
    if not layer_dir.is_dir():
        return False, 'no existing layer directory'
    for path in (report, manifest, conv, build):
        if not path.is_file():
            return False, 'missing ' + path.name + '; partial product is not reusable'
    if conv.read_bytes() != (NV / 'build-a01.py').read_bytes():
        return False, 'converter.source.py differs from the pinned build-a01.py'
    if build.read_bytes() != (NV / 'build-layer.py').read_bytes():
        return False, 'builder.source.py differs from the pinned build-layer.py'
    try:
        body = json.loads(manifest.read_text(encoding='utf-8'))
        rep = json.loads(report.read_text(encoding='utf-8'))
    except Exception as exc:
        return False, 'unreadable manifest/report: ' + str(exc)
    if body.get('schema') != 'cf6-native-layer-input.v1':
        return False, 'manifest schema rejected'
    if body.get('name') != name or body.get('source') != job['source']:
        return False, 'manifest identity differs from the ready job'
    if body.get('sourceSha256') != job['sourceSha256']:
        return False, 'source SVG SHA changed'
    if body.get('inputIndexSha256') != map_input_sha:
        return False, 'map-input SHA changed'
    inputs = body.get('inputs')
    if not isinstance(inputs, list):
        return False, 'manifest inputs missing'
    expected = {t['sha256']: t for t in expect_textures}
    if {i.get('sha256') for i in inputs} != set(expected):
        return False, 'manifest texture set differs from the source SVG textures'
    for item in inputs:
        rel = item.get('path', '')
        tex = (ROOT / rel).resolve()
        if not any(tex == root or root in tex.parents for root in ASSET_ROOTS):
            return False, 'texture outside owned asset roots: ' + rel
        if not tex.is_file():
            return False, 'texture missing from asset dir: ' + rel
        raw = tex.read_bytes()
        if len(raw) != item.get('bytes') or hashlib.sha256(raw).hexdigest() != item.get('sha256'):
            return False, 'texture original bytes changed: ' + rel
        if expected[item['sha256']]['bytes'] != item.get('bytes'):
            return False, 'texture byte count differs from source SVG: ' + rel
    if rep.get('schema') != 'cf6-native-layer-candidate.v1' or rep.get('name') != name:
        return False, 'report identity rejected'
    if rep.get('sourceSha256') != job['sourceSha256']:
        return False, 'report source SHA changed'
    state = rep.get('state', '')
    if expected:
        if not recipe.is_file() or recipe.stat().st_size == 0:
            return False, 'import recipe missing; partial product is not reusable'
        if not state.startswith('source generated'):
            return False, 'report state is not a completed source generation: ' + state
        return True, 'source snapshots + manifest + texture original bytes verified'
    if not state.startswith('native XFL assembled'):
        return False, 'zero-texture target without assembled state: ' + state
    candidate = ROOT / 'flashswf/backgrounds/cf6' / name
    closure = [candidate / (name + '.xfl'), candidate / 'DOMDocument.xml', candidate / 'PublishSettings.xml']
    if not all(p.is_file() for p in closure) or not (candidate / 'LIBRARY').is_dir():
        return False, 'assembled XFL closure incomplete'
    if len(list((candidate / 'LIBRARY').glob('*.xml'))) != rep.get('nativeSymbols'):
        return False, 'assembled LIBRARY symbol count differs from report'
    return True, 'source snapshots + manifest + assembled XFL closure verified'


def output_closure(layer_dir, name, job, texture_count):
    problems = []
    for leaf in ('report.json', 'texture-manifest.json', 'converter.source.py', 'builder.source.py'):
        if not (layer_dir / leaf).is_file():
            problems.append('missing ' + leaf)
    if texture_count > 0:
        if not (layer_dir / 'import-textures.jsfl').is_file():
            problems.append('missing import-textures.jsfl')
    else:
        candidate = ROOT / 'flashswf/backgrounds/cf6' / name
        for leaf in (name + '.xfl', 'DOMDocument.xml', 'PublishSettings.xml'):
            if not (candidate / leaf).is_file():
                problems.append('missing candidate ' + leaf)
    if problems:
        return problems
    try:
        manifest = json.loads((layer_dir / 'texture-manifest.json').read_text(encoding='utf-8'))
        if manifest.get('sourceSha256') != job['sourceSha256']:
            problems.append('fresh manifest source SHA mismatch')
        for item in manifest.get('inputs', []):
            tex = (ROOT / item['path']).resolve()
            if not any(tex == root or root in tex.parents for root in ASSET_ROOTS):
                problems.append('fresh texture outside owned asset roots: ' + item['path'])
            elif not tex.is_file() or hashlib.sha256(tex.read_bytes()).hexdigest() != item['sha256']:
                problems.append('fresh texture digest mismatch: ' + item['path'])
    except Exception as exc:
        problems.append('fresh manifest unreadable: ' + str(exc))
    return problems


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--only', nargs='*', default=None, help='restrict to exact target names')
    args = parser.parse_args()
    try:
        ready, pinned, jobs = ready_contract.load_ready()
    except ready_contract.ContractError as exc:
        raise SystemExit('ready contract rejected; batch refused: ' + str(exc))
    signal_sha = sha(SIGNAL)
    map_input_sha = sha(ready_contract.MAP_INPUT)
    map_input = json.loads(ready_contract.MAP_INPUT.read_text(encoding='utf-8'))['maps']
    for job in jobs:
        layers = {x['id']: x for x in map_input.get(job['map'], {}).get('layers', [])}
        entry = layers.get(job['layer'])
        if entry is None or entry['source']['svg'] != job['source']:
            raise SystemExit('ready job ' + job['name'] + ' absent from the live map-input; batch refused')
    if not PLAN.is_file():
        raise SystemExit('plan.json missing; run batch-plan.py --check first')
    plan = json.loads(PLAN.read_text(encoding='utf-8'))
    if plan.get('mapInput', {}).get('sha256') != map_input_sha:
        raise SystemExit('plan.json is stale (map-input changed); rerun batch-plan.py --check')
    plan_targets = {t['name']: t for t in plan.get('targets', [])}
    if set(plan_targets) != {j['name'] for j in jobs}:
        raise SystemExit('plan.json targets differ from the ready jobs; rerun batch-plan.py --check')
    for job in jobs:
        target = plan_targets[job['name']]
        if target.get('sourceSha256') != job['sourceSha256'] or target.get('source') != job['source']:
            raise SystemExit('plan.json source lock differs from the ready signal for ' + job['name'])
    if args.only:
        unknown = [n for n in args.only if n not in plan_targets]
        if unknown:
            raise SystemExit('--only names not in the locked plan: ' + repr(unknown))
    LOGS.mkdir(exist_ok=True)
    stamp = datetime.datetime.now().strftime('%Y%m%d-%H%M%S')
    log_path = LOGS / ('batch-' + stamp + '.log')
    log = {'startedAt': stamp, 'signalSha256': signal_sha, 'signalSchema': ready['schema'],
           'signalStatus': ready['status'], 'converterBundleSha256': ready.get('converterBundleSha256'),
           'dependencies': pinned, 'mapInputSha256': map_input_sha, 'targets': []}
    aborted = None
    for job in jobs:
        name = job['name']
        target = plan_targets[name]
        entry = {'name': name, 'map': job['map'], 'layer': job['layer']}
        if args.only and name not in args.only:
            entry['status'] = 'skipped(--only)'
            log['targets'].append(entry)
            continue
        if aborted:
            entry['status'] = 'skipped(batch aborted: ' + aborted + ')'
            log['targets'].append(entry)
            continue
        if target['status'] == 'blocked':
            entry['status'] = 'blocked'
            entry['gaps'] = target['gaps']
            log['targets'].append(entry)
            continue
        consumed = [(MAP_INPUT_REL, map_input_sha), (job['source'], job['sourceSha256'])]
        try:
            ready_contract.verify_unchanged(pinned, signal_sha, consumed)
        except ready_contract.ContractError as exc:
            aborted = 'dependency-or-input-mutated'
            entry['status'] = 'failed'
            entry['error'] = 'pre-target verification: ' + str(exc)
            log['targets'].append(entry)
            continue
        layer_dir = NV / 'layers' / name
        ok, why = reusable(layer_dir, name, job, map_input_sha, target.get('textures', []))
        if ok:
            entry['status'] = 'reused'
            entry['reason'] = why
            log['targets'].append(entry)
            continue
        entry['reuseRejected'] = why
        builder = target.get('builder')
        if builder:
            command = [sys.executable, '-X', 'utf8', '-B', builder['script']] + list(builder['args'])
            entry['builder'] = builder['script']
        else:
            command = [sys.executable, '-X', 'utf8', '-B', 'tools/cf6-map-runtime/native-vector/build-layer.py',
                       '--map', job['map'], '--layer', job['layer'], '--asset-dir', ready_contract.ASSET_DIR]
        if target['textureCount'] == 0:
            command.append('--assemble')
        run = subprocess.run(command, cwd=ROOT, capture_output=True, text=True, encoding='utf-8', errors='replace')
        entry['exitCode'] = run.returncode
        target_log = LOGS / (name + '-' + stamp + '.log')
        target_log.write_text('COMMAND: ' + ' '.join(command) + '\nEXIT: ' + str(run.returncode)
                              + '\nSTDOUT:\n' + run.stdout + '\nSTDERR:\n' + run.stderr, encoding='utf-8')
        entry['log'] = target_log.relative_to(ROOT).as_posix()
        try:
            ready_contract.verify_unchanged(pinned, signal_sha, consumed)
        except ready_contract.ContractError as exc:
            aborted = 'dependency-or-input-mutated'
            entry['status'] = 'failed'
            entry['error'] = 'post-target verification: ' + str(exc) + '; identity not mixed'
            log['targets'].append(entry)
            continue
        if run.returncode != 0:
            entry['status'] = 'failed'
            entry['error'] = (run.stderr.strip().splitlines() or ['no stderr'])[-1]
            log['targets'].append(entry)
            continue
        problems = output_closure(layer_dir, name, job, target['textureCount'])
        if problems:
            entry['status'] = 'failed'
            entry['error'] = 'incomplete output closure: ' + '; '.join(problems)
            log['targets'].append(entry)
            continue
        entry['status'] = 'assembled' if target['textureCount'] == 0 else 'source-generated'
        entry['stdout'] = run.stdout.strip().splitlines()[-1] if run.stdout.strip() else ''
        log['targets'].append(entry)
    by_name = {e['name']: e for e in log['targets']}
    for target in plan['targets']:
        e = by_name.get(target['name'])
        if not e:
            continue
        target['status'] = e['status']
        target['exitCode'] = e.get('exitCode')
        if e.get('error'):
            target.setdefault('gaps', []).append(e['error'])
        if e.get('log'):
            target['batchLog'] = e['log']
        if e.get('reason'):
            target['reuseEvidence'] = e['reason']
        if e.get('reuseRejected'):
            target['reuseRejected'] = e['reuseRejected']
    plan['signal'].update({'sha256': signal_sha, 'schema': ready['schema'], 'status': ready['status'],
                           'converterBundleSha256': ready.get('converterBundleSha256'), 'jobs': len(jobs)})
    plan['lastBatch'] = {'log': log_path.relative_to(ROOT).as_posix(), 'signalSha256': signal_sha,
                         'mapInputSha256': map_input_sha, 'startedAt': stamp}
    log_path.write_text(json.dumps(log, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    PLAN.write_text(json.dumps(plan, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    counts = {}
    for e in log['targets']:
        counts[e['status']] = counts.get(e['status'], 0) + 1
    print(json.dumps({'log': log_path.relative_to(ROOT).as_posix(), 'status': counts, 'aborted': aborted},
                     ensure_ascii=False, indent=2))
    if aborted or any(e['status'] == 'failed' for e in log['targets']):
        sys.exit(1)


if __name__ == '__main__':
    main()
