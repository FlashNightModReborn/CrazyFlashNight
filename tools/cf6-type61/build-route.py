def actor_entries(source):
    """All direct item identities consumed by the source, excluding generated boxes."""
    yield from source['actor']['equipment']
    for section in ('materialDeliveries','medicineDeliveries','ammoDeliveries','throwableDeliveries'):
        for rows in source[section].values(): yield from rows


def main():
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in build().items():
        if args.check:
            if not path.is_file() or path.read_bytes() != content:
                raise SystemExit('stale: ' + str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
        print(str(path.relative_to(ROOT)))


if __name__ == '__main__':
    main()
