def recipes(source):
    result=[]
    for i,entry in enumerate(source['actor']['equipment']):
        if not entry['name'].startswith('61式'): continue
        result.append(dict(recipeId='craft.cf6-type61.titanium.'+str(i),title='61计划·钛合金'+entry['name']+'升级',name='钛合金'+entry['name'],
                           price=source['titaniumUpgrade']['moneyPerPiece'],kprice=source['titaniumUpgrade']['kpointsPerPiece'],materials=['统合'+entry['name']+'#1']))
    return result


