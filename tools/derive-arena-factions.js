#!/usr/bin/env node
'use strict';

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const sourcePath = path.join(root, 'data', 'arena', 'arena_factions.json');
const teamsPath = path.join(root, 'data', 'arena', 'meta_teams.json');
const outputPath = path.join(root, 'launcher', 'web', 'modules', 'arena-factions.js');
const checkOnly = process.argv.indexOf('--check') >= 0;

function fail(message) {
    console.error('[arena-factions] FAIL: ' + message);
    process.exit(1);
}

function readSource() {
    let source;
    let teams;
    try {
        source = JSON.parse(fs.readFileSync(sourcePath, 'utf8'));
    } catch (error) {
        fail('cannot parse data/arena/arena_factions.json: ' + error.message);
    }
    try {
        teams = JSON.parse(fs.readFileSync(teamsPath, 'utf8'));
    } catch (error) {
        fail('cannot parse data/arena/meta_teams.json: ' + error.message);
    }
    if (!teams || Array.isArray(teams) || !teams.rosters || Array.isArray(teams.rosters)) {
        fail('meta_teams.json must contain a rosters object');
    }
    if (!source || Array.isArray(source) || source.schemaVersion !== 1
            || !source.factions || Array.isArray(source.factions)) {
        fail('source must be schemaVersion=1 with a factions object');
    }
    const names = Object.keys(source.factions);
    if (!names.length || new Set(names).size !== names.length) fail('factions must be non-empty and unique');
    names.forEach(name => {
        const item = source.factions[name];
        if (!name || !item || Array.isArray(item)) fail('invalid faction entry: ' + name);
        const roster = teams.rosters[name];
        if (!roster || !Array.isArray(roster.units)) fail(name + ': matching meta-team roster is required');
        if (typeof item.displayName !== 'string' || !item.displayName.trim()) fail(name + ': displayName must be non-blank');
        if (item.benchLevel !== null && (!Number.isInteger(item.benchLevel) || item.benchLevel < 1)) {
            fail(name + ': benchLevel must be null or a positive integer');
        }
        if (!['small', 'large', 'coalition'].includes(item.scale)) fail(name + ': invalid scale');
        if (typeof item.enabled !== 'boolean') fail(name + ': enabled must be boolean');
        if (item.units !== null) {
            if (!Array.isArray(item.units) || !item.units.length
                    || item.units.some(unit => typeof unit !== 'string' || !/^兵种\d+$/.test(unit))) {
                fail(name + ': units must be null or a non-empty 兵种N string array');
            }
            if (new Set(item.units).size !== item.units.length) fail(name + ': units contains duplicates');
            const rosterTypes = new Set(roster.units.map(unit => unit && unit.type));
            if (item.units.some(unit => !rosterTypes.has(unit))) fail(name + ': units contains a type outside its meta-team roster');
        }
    });
    return source;
}

function render(source) {
    return [
        '// AUTO-GENERATED by tools/derive-arena-factions.js from data/arena/arena_factions.json.',
        '// 请勿手改；修改 JSON 真源后重跑生成器。',
        '(function () {',
        '    \'use strict\';',
        '    if (typeof window === \'undefined\') return;',
        '    window.ArenaFactions = ' + JSON.stringify(source, null, 4).replace(/^/gm, '    ').trimStart() + ';',
        '})();',
        ''
    ].join('\n');
}

const rendered = render(readSource());
if (checkOnly) {
    if (!fs.existsSync(outputPath)) fail('generated output is missing');
    const actual = fs.readFileSync(outputPath, 'utf8').replace(/\r\n/g, '\n');
    if (actual !== rendered) fail('generated output is stale; run node tools/derive-arena-factions.js');
    console.log('[arena-factions] OK: generated Web module matches JSON authority source');
} else {
    fs.writeFileSync(outputPath, rendered, 'utf8');
    console.log('[arena-factions] wrote ' + path.relative(root, outputPath));
}
