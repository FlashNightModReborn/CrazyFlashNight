def validate_source(source,base,items):
    actor=source['actor']
    if (actor['level'],actor['experience'],source['startingMoney'],source['startingSkillPoints']) != (35,17372868,30000,1050):
        raise ValueError('Type61 initial actor budget changed')
    if source['blockedSkills'] != ['铁匠','口才','驾驶','烹饪','解密']:
        raise ValueError('Type61 blocked skill contract changed')
    if source['reviveNodes'] != ['TUTORIAL','A08','A16','A19'] or source['ordinaryConstellations'] != ['光剑天秤','光斧金牛','光刀狮子','光刃摩羯']:
        raise ValueError('Type61 revive or constellation allocation changed')
    if source['enhancementCaps'] != [dict(mapId=n,cap=v) for n,v in [('TUTORIAL',5),('A08',7),('A14',9),('A16',11)]]:
        raise ValueError('Type61 enhancement milestones changed')
    if source['titaniumUpgrade'] != {'moneyPerPiece':100000,'kpointsPerPiece':9000,'unlockNode':'A11'}:
        raise ValueError('Type61 upgrade price changed')
    if len(source['starterMainChoices'])!=3 or len(set(source['starterMainChoices']))!=3:
        raise ValueError('Type61 needs three distinct initial guns')
    for name in source['starterMainChoices']:
        if name not in items or items[name].findtext('use')!='长枪' or int(items[name].findtext('data/level','999'))>35:
            raise ValueError('Type61 starter gun is not usable at 35')
    if len(source['ammoCatalog'])!=13 or len(set(source['ammoCatalog']))!=13 or any(n not in items or items[n].findtext('use')!='弹夹' for n in source['ammoCatalog']):
        raise ValueError('Type61 ammunition catalog is incomplete')
    nodes={'TUTORIAL'}|{'A%02d'%n for n in range(1,20)}
    for category in ('materialDeliveries','medicineDeliveries','ammoDeliveries','throwableDeliveries'):
        for node,rows in source[category].items():
            if node not in nodes or type(rows)!=list or len(rows)>32: raise ValueError('invalid delivery node')
            for row in rows:
                if set(row)!={'name','count'} or row['name'] not in items or type(row['count'])!=int or not 1<=row['count']<=10000:
                    raise ValueError('invalid Type61 delivery item')
    maps={m['id']:m for m in base['maps']}; seen=set(); high=0
    for row in source['fieldSupplies']:
        key=(row.get('map'),row.get('wave'),row.get('phase'))
        if set(row)!={'map','wave','phase','high'} or key in seen or type(row['high'])!=bool or type(row['wave'])!=int:
            raise ValueError('invalid or duplicate Type61 field supply')
        if row['map'] not in maps or not 1<=row['wave']<=len(maps[row['map']]['stage']['Wave']['SubWave']):
            raise ValueError('field supply has no exact authored wave')
        if row['phase'] not in ('primary','robot') or row['phase']=='robot' and key!=('A20',6,'robot'):
            raise ValueError('invalid Type61 field phase')
        seen.add(key);high+=row['high']
    if len(seen)!=59 or high!=29: raise ValueError('Type61 field supply quota changed')
    if source['elevatorKeep']!={'A10':[0,3,9,11],'A13':[0]}:
        raise ValueError('Type61 elevator roster changed')
    levels={'TUTORIAL':35,**{r['mapId']:r['level'] for r in source['checkpoints']}}
    for node,rows in source['throwableDeliveries'].items():
        for row in rows:
            item=items[row['name']]
            if item.findtext('use')!='手雷' or int(item.findtext('data/level','999'))>levels[node]:
                raise ValueError('Throwable delivery is not usable at this checkpoint')
    for name,node in source['throwableShopNodes'].items():
        if node not in SHOP_NODES or name not in items or items[name].findtext('use')!='手雷':
            raise ValueError('Invalid throwable shop unlock')
    if source['bloodSwordChance']!=10 or source['bloodSwordNodes']!=['A04','A08','A12','A16']:
        raise ValueError('Type61 blood sword chance changed')


def build(source=None):
    source = json.loads(SOURCE.read_text('utf8')) if source is None else copy.deepcopy(source)
    if source['schema'] != 'cf6-type61-source.v1':
        raise ValueError('unsupported Type61 authoring schema')
    base = json.loads(BASE.read_text('utf8'))
    if (base['id'], base['routeId']) != ('cf6-sting', 'historical'):
        raise ValueError('Type61 requires the authored historical CF6 base')
    validate_source(source,base,item_catalog())
    chapter = copy.deepcopy(base)
    chapter['routeId'] = 'type61'
    chapter['title'] = source['title']
    for key in ('actor', 'startingMoney', 'startingSkillPoints'):
        chapter[key] = copy.deepcopy(source[key])
    chapter['economy']['choices'] = []
    chapter['type61'] = {key: copy.deepcopy(value) for key, value in source.items()
                         if key not in ('schema', 'title', 'actor', 'startingMoney', 'startingSkillPoints')}
    checkpoints = chapter['type61']['checkpoints']
    if [row['mapId'] for row in checkpoints] != ['A%02d' % n for n in range(1, 20)]:
        raise ValueError('Type61 checkpoints must be ordered A01 to A19')
    expected = {'money': 4720000, 'kpoints': 100000, 'stones': 10000, 'skillPoints': 1640}
    for key, total in expected.items():
        if any(type(row[key]) is not int or row[key] < 0 for row in checkpoints) or sum(row[key] for row in checkpoints) != total:
            raise ValueError('Type61 fixed budget mismatch: ' + key)
    levels=[r['level'] for r in checkpoints]
    if any(type(n)!=int for n in levels) or levels[0]!=36 or levels[-1]!=60 or levels!=sorted(set(levels)):
        raise ValueError('invalid Type61 checkpoint growth')
    config=chapter['type61']; items=item_catalog()
    choices, starter, middle, advanced, replacements=make_choices(source, base)
    config['choicePoolIds']=[p['id'] for p in choices['pools']]
    config['a04ReplacementPacks']=replacements
    config['midMods']=MID_MODS
    deliveries={key:[] for key in ['TUTORIAL']+[r['mapId'] for r in checkpoints]}
    for category in ('materialDeliveries','medicineDeliveries','ammoDeliveries','throwableDeliveries'):
        for node,rows in source[category].items(): deliveries[node].extend(copy.deepcopy(rows))
    # Initial main ammunition follows the chosen gun inside the same choice transaction.
    deliveries['TUTORIAL']=[r for r in deliveries['TUTORIAL'] if r['name']!='突击步枪通用弹药']
    first_drugs=['大HP药剂','大MP药剂','净化药剂','狴犴·零型','狻猊·一型','囚牛·一型','睚眦·一型','螭吻·一型']
    deliveries['TUTORIAL'].sort(key=lambda r:first_drugs.index(r['name']) if r['name'] in first_drugs else len(first_drugs))
    for row in checkpoints:
        if row['stones']: deliveries[row['mapId']].append(dict(name='强化石',count=row['stones']))
    for node in source['reviveNodes']: deliveries[node].append(dict(name='复活币',count=1))
    deliveries['TUTORIAL'].extend([dict(name=starter,count=1),dict(name='战术鱼骨零件',count=1),dict(name='高强度合金',count=1)])
    config['initialConstellationNode']='TUTORIAL'
    for node in source['bloodSwordNodes']: deliveries[node].append(dict(name='61计划星座机缘箱',count=1))
    for node in ('A04','A08'): deliveries[node].append(dict(name=middle,count=1))
    for node in ('A12','A16','A19'): deliveries[node].append(dict(name=advanced,count=1))
    config['deliveryItems']=deliveries
    skill_rows=ET.parse(ROOT/'data/skills/skills.xml').findall('Skill')
    trainer=[s.findtext('Name') for s in skill_rows if s.findtext('Name') and 1<=int(s.findtext('UnlockLevel','999'))<=60 and s.findtext('Name') not in source['blockedSkills']]
    config['learnableSkills']=trainer
    def obsolete(name):
        return name in ('金币','金钱','K点','技能点','经验值') or items.get(name) is not None and items[name].findtext('use') in ('药剂','弹夹','战场补给')
    for stage in chapter['maps']:
        native=stage['stage']; node=stage['id']
        native['Pickups']['Pickup']=[p for p in native.get('Pickups',{}).get('Pickup',[]) if not obsolete(p['Name'])]
        if node == 'TUTORIAL':
            stage['dialogue'][1]['text']='开局会随机赠送一把普通星座武器。初始配给到账后，打开装备界面的背包，使用“61计划初始主枪自选箱”选择主枪，再装入长枪栏。药品可放入药剂栏，材料与多余物资可在整备中查看。'
            for event in native['Event']:
                if event.get('EventName') == 'Start':
                    event.pop('Guidance', None)
                    event['Message']='61计划训练：先在装备界面的背包打开初始主枪自选箱，选择并装备主枪。随机星座武器和配给已直接入包；确认药弹后从右侧大门进入A01。'
        # No historical consumable/choice layer is allowed to shadow the fixed Type61 quota.
        for enemy in all_enemies(stage):
            parameters=enemy.setdefault('Parameters',{})
            if '掉落物' in parameters: parameters['掉落物']=[d for d in parameters['掉落物'] if not obsolete(d['名字'])]
        if node in source['elevatorKeep']:
            enemies=native['Wave']['SubWave'][0]['EnemyGroup']['Enemy']
            native['Wave']['SubWave'][0]['EnemyGroup']['Enemy']=[enemies[i] for i in source['elevatorKeep'][node]]
            for enemy in native['Wave']['SubWave'][0]['EnemyGroup']['Enemy']: enemy.setdefault('Parameters',{})['cf6DifficultyScale']=2.5
        encounters.apply(stage,items)
        for wave_index,wave in enumerate(native['Wave']['SubWave']):
            candidates=[e for e in wave['EnemyGroup']['Enemy'] if e.get('Quantity')==1]
            if candidates: candidates[0].setdefault('Parameters',{})['cf6Type61FieldWave']=wave_index+1
        boss=stage.get('bossEncounter')
        if boss:
            for enemy in all_enemies(stage):
                if enemy.get('InstanceName') == boss['instanceName'] or enemy not in [e for w in native['Wave']['SubWave'] for e in w['EnemyGroup']['Enemy']]:
                    enemy.setdefault('Parameters',{})['cf6DifficultyScale']=2.5
        if node in ('A03','A09','A14','A18'):
            carrier=next(e for e in all_enemies(stage) if e.get('Quantity')==1 and not e.get('Parameters',{}).get('cf6EliteQuota'))
            carrier.setdefault('Parameters',{})['cf6Type61MidMod']=True
        for npc in native.get('Instances',{}).get('Instance',[]):
            if npc.get('Identifier')=='生存战-迷之盔甲君':
                npc['Parameters'].update({'商店检索名':'书中-CF6六一-'+node,'技能检索名':'书中-CF6六一-'+node,'任务名':'书中-CF6六一-'+node,'可学的技能':dict(enumerate(trainer))})
        if node=='A05':
            basic=native['BasicInformation']
            native.setdefault('Instances',{}).setdefault('Instance',[]).append(dict(Identifier='生存战-迷之盔甲君',x=basic['PlayerX']+80,y=basic['PlayerY'],InitializeParametersBeforeAttach=True,
                Parameters={'商店检索名':'书中-CF6六一-A05','技能检索名':'书中-CF6六一-A05','任务名':'书中-CF6六一-A05','可学的技能':dict(enumerate(trainer)),'默认对话':[]}))
    outputs={OUTPUT:encoded(chapter),SOURCE.with_name('choice-rewards.fragment.json'):encoded(choices),SOURCE.with_name('recipes.generated.json'):encoded(recipes(source)),
             ROOT/'data/items/消耗品_CF6六一配给.xml':extra_items(source)}
    acquisition=route_plan(source,items)
    gold_weapons,_,_=channels()
    common=['技能点','K点','强化石']+source['ammoCatalog']+list(dict.fromkeys(r['name'] for rows in source['medicineDeliveries'].values() for r in rows))+MID_MODS+['传感器','高耐力橡胶','红外夜视仪','战术鱼骨零件']
    oldshops=['35','35','40','45','55','60']
    shop_ids=[]
    for index,node in enumerate(SHOP_NODES):
        old=json.loads((ROOT/('data/shops/npcs/书中-CF6毒刺-'+oldshops[index]+'级.json')).read_text('utf8'))
        names=common+list(old['catalog'].values())+[n for n,at in acquisition['cash'].items() if at<=node]
        names=[n for n in names if n not in source['throwableShopNodes'] or source['throwableShopNodes'][n]<=node]
        names += [n for n,at in source['throwableShopNodes'].items() if at<=node]
        names=[n for n in names if n not in ('普通hp药剂','普通mp药剂') and n not in source['ordinaryConstellations'] and n!='血色光剑天秤' and not n.startswith('钛合金61')]
        names=[n for n in names if items[n].findtext('type')!='武器' or n in gold_weapons]
        for n in list(names):
            ammo=items[n].findtext('data/clipname')
            if ammo and ammo not in names: names.append(ammo)
        names=list(dict.fromkeys(names))
        if any(n not in items for n in names): raise ValueError('unknown Type61 shop item')
        shop_id='书中-CF6六一-'+node;shop_ids.append(shop_id)
        outputs[ROOT/('data/shops/npcs/'+shop_id+'.json')]=encoded(dict(schema='npc-shop.v2',shopId=shop_id,title='61计划整备 · '+node,catalog=dict(enumerate(names))))
    config['shopIds']=shop_ids
    config['kShopEarly']=['强化石']+source['ammoCatalog']
    config['kShopLate']=['SVD','钛合金P90','战术巴雷特']
    config['kShopUnlocks']=acquisition['kpoints']
    config['recipeUnlocks']={r['recipeId']:source['titaniumUpgrade']['unlockNode'] for r in recipes(source)}
    for category in ('进阶防具','铁枪会'):
        for row in json.loads((ROOT/('data/crafting/'+category+'.json')).read_text('utf8')):
            if row['name'].startswith('统合61式'): config['recipeUnlocks'][row['recipeId']]='A05'
            if row['name']=='GM6_LYNX': config['recipeUnlocks'][row['recipeId']]='A11'
            if row['name']=='钛合金QJZ171': config['recipeUnlocks'][row['recipeId']]='A16'
    config['recipeUnlocks'].update(acquisition['recipes'])
    outputs[OUTPUT]=encoded(chapter)
    outputs[SOURCE.with_name('acquisition.generated.json')]=encoded(acquisition)
    fixture='// Generated test-only Type61 configuration; production reads the route runtime JSON.\nclass org.flashNight.arki.scene.Cf6Type61Fixture {\n'
