#!/usr/bin/env node
'use strict';
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const source = path.join(root, 'launcher/data/guidance-catalog.json');
const target = path.join(root, 'launcher/web/generated/guidance-catalog.js');
const catalog = JSON.parse(fs.readFileSync(source, 'utf8').replace(/^\uFEFF/, ''));
const ids = new Set(), legacy = new Set();
function validateVisual(visual) {
    if (visual == null) return;
    if (!Array.isArray(visual) || !visual.length || visual.length > 48) throw Error('Invalid guide visual');
    for (const node of visual) {
        const fields = node && node.type === 'mouse' ? ['type','x','y','width','height'] : ['type','x','y','width','height','text','fontSize'];
        if (!node || !['key','text','mouse'].includes(node.type) || Object.keys(node).length !== fields.length || fields.some(k=>!Object.hasOwn(node,k))
            || ['x','y','width','height'].some(k=>!Number.isFinite(node[k])) || node.x < 0 || node.y < 0
            || node.width < 1 || node.height < 1 || node.x + node.width > 1024 || node.y + node.height > 576
            || (node.type !== 'mouse' && (typeof node.text !== 'string' || !node.text.trim() || node.text.length > 80
                || /\{(?!left\}|right\}|up\}|down\}|attack\}|jump\}|interact\})/.test(node.text)
                || !Number.isFinite(node.fontSize) || node.fontSize < 10 || node.fontSize > 32))) throw Error('Invalid guide visual element');
    }
}
if (catalog.version !== 1 || !Array.isArray(catalog.guides) || catalog.guides.length > 64) throw Error('Invalid guidance catalog');
if (catalog.keyLabels != null && (typeof catalog.keyLabels !== 'object' || Array.isArray(catalog.keyLabels) || Object.keys(catalog.keyLabels).length > 64
    || Object.entries(catalog.keyLabels).some(([name,label])=>!name.trim() || name.length > 24 || /[\x00-\x1f\x7f]/.test(name)
        || typeof label !== 'string' || !label.trim() || label.length > 8 || /[\x00-\x1f\x7f]/.test(label)))) throw Error('Invalid key labels');
for (const g of catalog.guides) {
    if (!/^[a-z][a-z-]{1,31}$/.test(g.id) || ids.has(g.id) || legacy.has(g.legacy)
        || !['scene','tutorial'].includes(g.kind) || (g.surface != null && (g.surface !== 'help' || g.kind !== 'tutorial'))
        || typeof g.title !== 'string' || !g.title.trim() || g.title.length > 80
        || typeof g.legacy !== 'string' || !g.legacy.trim() || !Array.isArray(g.pages) || !g.pages.length || g.pages.length > 16) throw Error('Invalid guide: ' + g.id);
    ids.add(g.id); legacy.add(g.legacy);
    for (const p of g.pages) {
        if (typeof p.title !== 'string' || !p.title.trim() || p.title.length > 80
        || typeof p.text !== 'string' || !p.text.trim() || p.text.length > 3000
        || /\{(?!left\}|right\}|up\}|down\}|attack\}|jump\}|interact\})/.test(p.text)
        || (p.image != null && (typeof p.image !== 'string' || !p.image.startsWith('flashswf/images/') || /\.\.|\\|:/.test(p.image)))) throw Error('Invalid page: ' + g.id);
        validateVisual(p.visual);
    }
}
for(const id of ['start','map','combat','run','pickup','crate','crate-safe'])if(!ids.has(id))throw Error('U8 guide missing: '+id);
const output = '// Generated by tools/generate-guidance-catalog.js; source: launcher/data/guidance-catalog.json\n'
    + '(function(root){ var data = ' + JSON.stringify(catalog, null, 2) + ';\n'
    + 'if(typeof module!=="undefined"&&module.exports)module.exports=data; if(root)root.GuidanceCatalog=data; })(typeof window!=="undefined"?window:globalThis);\n';
if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target,'utf8') !== output) throw Error('Guidance catalog projection is stale');
} else fs.writeFileSync(target, output, 'utf8');
console.log('Guidance catalog: '+ids.size+' guides, projection ' + (process.argv.includes('--check') ? 'verified' : 'generated'));
const journeys = JSON.parse(fs.readFileSync(path.join(root,'launcher/data/tutorial-journeys.json'),'utf8'));
const features = journeys.domains.flatMap(d=>d.features), covered = journeys.journeys.map(j=>j.id);
const domainIds=journeys.domains.map(d=>d.id);
if (journeys.version !== 1 || new Set(covered).size !== covered.length || new Set(domainIds).size !== domainIds.length
    || journeys.domains.some(d=>!d.features.length||d.features.some(id=>!journeys.journeys.some(j=>j.id===id&&j.domain===d.id)))) throw Error('Tutorial feature coverage incomplete');
function point(p){return p&&Number.isFinite(p.x)&&Number.isFinite(p.y)&&p.x>=0&&p.x<=1&&p.y>=0&&p.y<=1;}
for(const journey of journeys.journeys) {
    if(journey.version!==1||!domainIds.includes(journey.domain)||!journey.steps.length||journey.steps.length>128)throw Error('Invalid journey');
    for(const step of journey.steps)if(step.action!=='click'||!step.expected||!/^[-a-z0-9]{1,48}$/.test(step.target)
        || !point(step.point) || (step.ctrl!=null&&typeof step.ctrl!=='boolean')
        || (step.path!=null&&(!Array.isArray(step.path)||step.path.length>64||step.path.some(p=>!point(p)))))throw Error('Invalid semantic step');
}
const journeysTarget=path.join(root,'launcher/web/generated/tutorial-journeys.js');
const journeysOutput='// Generated by tools/generate-guidance-catalog.js\n(function(root){var data='+JSON.stringify(journeys,null,2)+';\nif(typeof module!=="undefined"&&module.exports)module.exports=data; if(root)root.TutorialJourneys=data;})(typeof window!=="undefined"?window:globalThis);\n';
if(process.argv.includes('--check')) {
    if(!fs.existsSync(journeysTarget)||fs.readFileSync(journeysTarget,'utf8')!==journeysOutput)throw Error('Tutorial journeys projection stale');
} else fs.writeFileSync(journeysTarget,journeysOutput,'utf8');
console.log('Tutorial coverage: '+features.length+' features, '+covered.length+' journeys');
