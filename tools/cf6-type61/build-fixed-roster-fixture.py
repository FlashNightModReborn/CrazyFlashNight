"""Generate bounded native test functions from the actual fixed-instance projection."""
import argparse
import importlib.util
import json
from pathlib import Path
import re
import shutil
import fixed_roster as fixed

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
TARGET = ROOT / 'scripts/类定义/org/flashNight/arki/scene/Cf6FixedRosterFixture.as'


def generate():
    spec = importlib.util.spec_from_file_location('fixed_fixture_builder', HERE / 'build-route.py')
    builder = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(builder)
    book = json.loads(builder.build(include_fixed=False)[builder.OUTPUT])
    compiled = fixed.compile_slots(book)
    projected = fixed.apply(book, compiled)
    groups = []
    for stage in projected['maps']:
        for enemy in builder.all_enemies(stage):
            if 'cf6FixedSlots' in enemy.get('Parameters', {}):
                groups.append(dict(Quantity=enemy['Quantity'], Parameters={key: enemy['Parameters'][key]
                              for key in ('cf6FixedSlots', 'cf6RosterVersion')}))
    source = '// Generated by tools/cf6-type61/build-fixed-roster-fixture.py; native tests only.\n'
    source += 'class org.flashNight.arki.scene.Cf6FixedRosterFixture {\n'
    source += '    public static function groups():Array {return [' + ','.join('part' + str(i) + '()' for i in range(len(groups))) + '];}\n'
    for i, group in enumerate(groups):
        literal = json.dumps(group, ensure_ascii=False, separators=(',', ':'))
        literal = re.sub(r'"([A-Za-z_\u4e00-\u9fa5][A-Za-z0-9_\u4e00-\u9fa5]*)"(?=\s*:)', r'\1', literal)
        if len(literal.encode('utf-8')) > 20000:
            raise ValueError('Native fixed group needs a smaller test function')
        source += '    private static function part' + str(i) + '():Object {return ' + literal + ';}\n'
    return b'\xef\xbb\xbf' + (source + '}\n').encode('utf-8')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = generate()
    if args.check:
        if not TARGET.exists() or TARGET.read_bytes() != content:
            raise ValueError('Stale fixed roster native fixture')
    else:
        if not TARGET.exists():
            shutil.copyfile(TARGET.with_name('Cf6Type61Fixture.as'), TARGET)
        if TARGET.read_bytes()[:3] != b'\xef\xbb\xbf':
            raise ValueError('Native fixture BOM missing')
        TARGET.write_bytes(content)
    print(json.dumps(dict(bytes=len(content), check=args.check, scope='native-test-only')))
