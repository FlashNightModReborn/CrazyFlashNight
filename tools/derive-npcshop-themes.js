#!/usr/bin/env node
'use strict';

// 由 data/shops/list.xml（商店清单）与 data/rag/npc_state_db.json（NPC→阵营权威）派生
// NPC 商店的阵营主题模块。配色本身是设计输入，维护在下方 FACTION_THEMES；
// shopId→阵营解析优先取 npc_state_db，无 NPC 社交记录的店主持 OVERRIDES
// （依据 data/dialogues/npc_dialogue_<阵营>.xml 的归属分组人工核定）。

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const shopsListPath = path.join(root, 'data', 'shops', 'list.xml');
const npcStatePath = path.join(root, 'data', 'rag', 'npc_state_db.json');
const outputPath = path.join(root, 'launcher', 'web', 'modules', 'npcshop-themes.js');
const checkOnly = process.argv.indexOf('--check') >= 0;

function fail(message) {
    console.error('[npcshop-themes] FAIL: ' + message);
    process.exit(1);
}

// 设计输入：accent=阵营主色，dark=面板底色（深色），light=两栏 UI 染色（浅色）。
// 定色口径（2026-10-12 与需求方确认）：A兵团=红，黑铁会=黑白，军阀=棕绿，
// 摇滚公园=红蓝黄三色混合，其余阵营暂用灰白。
const FACTION_THEMES = {
    'A兵团': { accent: '#c0392f', dark: '#1c0e0d', light: '#dd8d82' },
    'A兵团元老': { accent: '#a93226', dark: '#170b0a', light: '#cf8075' },
    '黑铁会': { accent: '#d6d8db', dark: '#0c0c0e', light: '#b7bbc1' },
    '联合大学': { accent: '#c2c8cf', dark: '#14161a', light: '#d6dade' },
    '摇滚公园': { accent: '#d8443c', dark: '#12131f', light: '#e8c45a' },
    '军阀': { accent: '#857c46', dark: '#16150c', light: '#b0a67a' },
    '商人': { accent: '#c2c8cf', dark: '#14161a', light: '#d6dade' },
    '闲杂人等': { accent: '#c2c8cf', dark: '#14161a', light: '#d6dade' },
    '彩蛋': { accent: '#c2c8cf', dark: '#14161a', light: '#d6dade' },
    '成员': { accent: '#c2c8cf', dark: '#14161a', light: '#d6dade' }
};
const DEFAULT_THEME = { accent: '#c2c8cf', dark: '#14161a', light: '#d6dade' };

// npc_state_db.json 无该 NPC 社交记录时的 shopId→阵营人工核定表。
const OVERRIDES = {
    '调酒师': '闲杂人等',
    '武器大师': '闲杂人等',
    '幸存老兵-暂时停用': '闲杂人等',
    '虎妙': '彩蛋',
    '书中-迷之盔甲君': '彩蛋',
    '阿卡': '成员'
};

function readShopIds() {
    const xml = fs.readFileSync(shopsListPath, 'utf8');
    const ids = [];
    const pattern = /<shops>npcs\/(.+)\.json<\/shops>/g;
    let match;
    while ((match = pattern.exec(xml)) !== null) ids.push(match[1]);
    if (!ids.length) fail('data/shops/list.xml yielded no shop ids');
    if (new Set(ids).size !== ids.length) fail('duplicate shop id in list.xml');
    return ids;
}

function readNpcFactions() {
    let db;
    try {
        db = JSON.parse(fs.readFileSync(npcStatePath, 'utf8'));
    } catch (error) {
        fail('cannot parse data/rag/npc_state_db.json: ' + error.message);
    }
    if (!db || Array.isArray(db) || typeof db !== 'object') fail('npc_state_db.json must be an object');
    return db;
}

function build() {
    const shopIds = readShopIds();
    const db = readNpcFactions();
    const shops = {};
    shopIds.forEach(shopId => {
        let faction = null;
        if (db[shopId] && typeof db[shopId].faction === 'string' && db[shopId].faction.trim()) {
            faction = db[shopId].faction.trim();
        } else if (Object.prototype.hasOwnProperty.call(OVERRIDES, shopId)) {
            faction = OVERRIDES[shopId];
        }
        if (!faction) fail(shopId + ': no faction in npc_state_db.json and no override; add one to OVERRIDES');
        if (!FACTION_THEMES[faction]) fail(shopId + ': faction "' + faction + '" has no theme; add one to FACTION_THEMES');
        shops[shopId] = faction;
    });
    return { version: 1, fallback: '_default', factions: Object.assign({ _default: DEFAULT_THEME }, FACTION_THEMES), shops: shops };
}

function render(data) {
    return [
        '// AUTO-GENERATED by tools/derive-npcshop-themes.js from data/shops/list.xml + data/rag/npc_state_db.json.',
        '// 请勿手改；阵营归属改真源或生成器 OVERRIDES 后重跑生成器，配色改生成器 FACTION_THEMES。',
        '(function () {',
        '    \'use strict\';',
        '    if (typeof window === \'undefined\') return;',
        '    window.NpcShopThemes = ' + JSON.stringify(data, null, 4).replace(/^/gm, '    ').trimStart() + ';',
        '})();',
        ''
    ].join('\n');
}

const rendered = render(build());
if (checkOnly) {
    if (!fs.existsSync(outputPath)) fail('generated output is missing');
    const actual = fs.readFileSync(outputPath, 'utf8').replace(/\r\n/g, '\n');
    if (actual !== rendered) fail('generated output is stale; run node tools/derive-npcshop-themes.js');
    console.log('[npcshop-themes] OK: generated Web module matches authority sources');
} else {
    fs.writeFileSync(outputPath, rendered, 'utf8');
    console.log('[npcshop-themes] wrote ' + path.relative(root, outputPath));
}
