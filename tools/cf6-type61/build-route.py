def xml_bytes(root):
    ET.indent(root, space='    ')
    return ET.tostring(root, encoding='utf-8', xml_declaration=True) + b'\n'


def register_xml(path, tag, names, marker):
    text = path.read_text('utf-8-sig')
    block = '\n  <!-- BEGIN ' + marker + ' -->\n' + ''.join('  <%s>%s</%s>\n' % (tag, n, tag) for n in names) + '  <!-- END ' + marker + ' -->\n'
    text = re.sub(r'\n\s*<!-- BEGIN ' + re.escape(marker) + r' -->.*?<!-- END ' + re.escape(marker) + r' -->\s*', '\n', text, flags=re.S)
    return text.replace('</root>', block + '</root>').encode('utf8')


def all_enemies(stage):
    for wave in stage['stage']['Wave']['SubWave']:
        yield from wave['EnemyGroup']['Enemy']
    for phase in (stage.get('bossEncounter', {}), stage.get('bossEncounter', {}).get('nextPhase', {})):
        for group in phase.get('groups', []):
            yield from group['enemies']


def make_choices(source, base):
    bundles, pools = [], []
    def bundle(token, name, count=1, grade='medium'):
        identity = 'cf6.type61.' + token
        # Two short guns must be separate equipment instances; item lists enforce uniqueness.
        if count == 2:
            meta = item_catalog()[name]
            result = dict(id=identity, name=name+'双持', title=name+'双持', description='本配额提供两把独立短枪，弹药从定向补给与商店取得。', grade=grade,
                          weapon=name, weaponCount=2, mods=[], consumables=[], checkpointAmmo=True)
        else:
            result = dict(id=identity, name=name, title=name, description='本局使用；弹药与必要药品另行配给。插件可从材料界面安装，副武器弹种可在整备商店补购。', grade=grade, items=[dict(itemName=name, quantity=1)])
        bundles.append(result)
        return identity
    def pool(token, title, ids, draw=None):
        identity = 'cf6.type61.' + token
        pools.append(dict(id=identity, version=1, title=title, itemName=title, scope=dict(kind='book', bookId='cf6-sting', routeId='type61'),
                          maxItemLevel=60, chooseCount=1, rerolls=0,
                          groups=[dict(id='options', draw=len(ids) if draw is None else draw,
                                       entries=[dict(bundleId=i, weight=1) for i in ids])]))
        return title
    starter = pool('starter', '61计划初始主枪自选箱', [bundle('starter.'+str(i), n) for i, n in enumerate(source['starterMainChoices'])])
    for row in bundles:
        if row['id'].startswith('cf6.type61.starter.'):
            ammo=item_catalog()[row['items'][0]['itemName']].findtext('data/clipname')
            row['items'].append(dict(itemName=ammo,quantity=8))
    middle = pool('mods.medium', '61计划中级插件自选箱', [bundle('mid.'+str(i), n) for i,n in enumerate(MID_MODS)])
    advanced = pool('mods.high', '61计划高级插件自选箱', [bundle('high.'+str(i), n, grade='high') for i,n in enumerate(HIGH_MODS)])
    # Each possible A04 draw retains the original item as an option. Selecting the open
    # gun consumes the same allowance; it never creates a second weapon quota.
    open_id = bundle('a04.open', 'HKSL8EX')
    replacements = {}
    row = next(r for r in base['economy']['randomWeapons'] if r['mapId'] == 'A04')
    for i, option in enumerate(row['choices']):
        name = option['weapon']
        if name == 'HKSL8EX':
            replacements[name] = ''
            continue
        original = bundle('a04.original.'+str(i), name, option.get('weaponCount', 1))
        replacements[name] = pool('a04.'+str(i), '61计划改装主枪箱'+str(i+1), [original, open_id])
    return dict(schema='choice-rewards.v1', bundles=bundles, pools=pools), starter, middle, advanced, replacements


