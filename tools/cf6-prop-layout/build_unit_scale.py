"""Generate the seven explicitly measured CF6 humanoid scale rules."""
import argparse
import hashlib
import json
import math
from pathlib import Path
import shutil

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
TARGET = ROOT / 'scripts/类定义/org/flashNight/arki/unit/Cf6BodyScaleRules.as'


def build():
    policy = json.loads((HERE / 'scale-policy.json').read_text(encoding='utf-8'))
    rows = policy['humanoids']
    if {r['unitId'] for r in rows} != {461, 462, 464, 466, 467, 468, 469}:
        raise ValueError('unreviewed humanoid scope')
    if len(rows) != 7 or len({r['linkage'] for r in rows}) != 7:
        raise ValueError('duplicate humanoid')
    lines = []
    for row in rows:
        size = row['nativeStandingBodyHeight']
        if not math.isfinite(size) or size <= 0:
            raise ValueError('invalid body height')
        for path, sha in row['nativeSources'].items():
            if hashlib.sha256((ROOT / path).read_bytes()).hexdigest() != sha:
                raise ValueError('body source drift: ' + path)
        lines.append('        if (unitType == ' + json.dumps(row['linkage'], ensure_ascii=False) + ') return ' + repr(size) + ';')
    ref = policy['reference']
    source = '''// Generated by tools/cf6-prop-layout/build_unit_scale.py; edit scale-policy.json.
// Body-only native standing measurements; no player, camera or nonhumanoid changes.
class org.flashNight.arki.unit.Cf6BodyScaleRules {
    public static function nativeBodyHeight(unitType:String):Number {
''' + '\n'.join(lines) + '''
        return 0;
    }

    public static function heightScale(unitType:String, heightCm:Number, legacyScale:Number):Number {
        var bodyHeight:Number = nativeBodyHeight(unitType);
        if (bodyHeight <= 0 || typeof(heightCm) != "number" || isNaN(heightCm) || !isFinite(heightCm) || heightCm <= 0) return legacyScale;
        return heightCm * 100 * ''' + repr(ref['relaxedStandingBodyPixels']) + ' / (' + repr(ref['heightCm']) + ''' * bodyHeight);
    }
}
'''
    return b'\xef\xbb\xbf' + source.encode('utf-8')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = build()
    if args.check:
        if not TARGET.exists() or TARGET.read_bytes() != content:
            raise SystemExit('CF6 unit scale source drift')
    else:
        if not TARGET.exists():
            shutil.copyfile(TARGET.with_name('UnitUtil.as'), TARGET)
        TARGET.write_bytes(content)
    print('CF6 unit scale: 7 exact linkages OK')
