#!/usr/bin/env node
"use strict";

const crypto = require("crypto");
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const SOURCE_PATH = path.join(ROOT, "data", "arena", "meta_teams.json");
const OUTPUT_PATH = path.join(ROOT, "launcher", "web", "modules", "arena-custom-presets.js");

const MAX_SIDE_COUNT = 20;
const BENCH_ROSTER = [
  { id: 44, level: 30, count: 1 },
  { id: 45, level: 30, count: 1 },
  { id: 48, level: 30, count: 1 },
  { id: 49, level: 30, count: 1 },
];

function stableHash(text) {
  return crypto.createHash("sha1").update(String(text), "utf8").digest("hex");
}

function stableSeed(text) {
  return parseInt(stableHash(text).slice(0, 8), 16) % 1000000;
}

function normalizeUnitId(value) {
  if (value == null) return null;
  const text = String(value);
  const match = text.match(/^兵种([0-9]+)$/) || text.match(/^u([0-9]+)$/i);
  if (match) return Number(match[1]);
  if (/^[0-9]+$/.test(text)) return Number(text);
  return null;
}

function rosterToCode(roster) {
  return roster
    .map((entry) => `u${entry.id}@${entry.level}x${entry.count}`)
    .join(",");
}

function memberToRoster(member) {
  const id = member.id != null ? Number(member.id) : normalizeUnitId(member.type);
  const level = Number(member.level);
  const count = Number(member.count);
  if (!Number.isFinite(id) || id <= 0) return null;
  if (!Number.isFinite(level) || level <= 0) return null;
  if (!Number.isFinite(count) || count <= 0) return null;
  return {
    id: Math.floor(id),
    level: Math.floor(level),
    count: Math.floor(count),
    name: member.name || `兵种${id}`,
  };
}

function summarizeRoster(roster) {
  return roster
    .slice(0, 3)
    .map((entry) => `${entry.name || `兵种${entry.id}`}x${entry.count}`)
    .join(" / ") + (roster.length > 3 ? " / ..." : "");
}

function sanitizeLabel(text) {
  return String(text || "")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, 80);
}

function buildPresets(catalog) {
  if (!catalog || !Array.isArray(catalog.teams)) {
    throw new Error("data/arena/meta_teams.json must contain teams[]");
  }

  const presets = [];
  const skipped = [];
  catalog.teams.forEach((team) => {
    const roster = (team.members || [])
      .map(memberToRoster)
      .filter(Boolean);
    const total = roster.reduce((sum, entry) => sum + entry.count, 0);
    if (!roster.length || total > MAX_SIDE_COUNT) {
      skipped.push({ id: team.id, unitCount: total || team.unitCount || 0 });
      return;
    }

    const seed = stableSeed(team.id);
    const code = [
      "CF7ARENA:v1",
      "mode=mvm",
      `seed=${seed}`,
      `blue=${rosterToCode(BENCH_ROSTER)}`,
      `red=${rosterToCode(roster)}`,
    ].join(";");

    const faction = team.faction || "unknown";
    const label = sanitizeLabel(
      `${team.sourceName || team.sourceStage || "关卡组合"} #${team.group || "0"} · ${faction} · ${total}体 Lv${team.levelMin || "?"}-${team.levelMax || "?"}`
    );
    presets.push({
      id: `meta-${stableHash(team.id).slice(0, 12)}`,
      label,
      description: `${team.sourceStage || team.id} · ${summarizeRoster(roster)}`,
      code,
      source: "meta-team",
      sourceId: team.id,
      sourceStage: team.sourceStage || "",
      sourceName: team.sourceName || "",
      faction,
      unitCount: total,
      levelMin: team.levelMin || null,
      levelMax: team.levelMax || null,
      powerRating: team.powerRating || 0,
    });
  });

  return { presets, skipped };
}

function buildModule() {
  const catalog = JSON.parse(fs.readFileSync(SOURCE_PATH, "utf8"));
  const { presets, skipped } = buildPresets(catalog);
  if (!presets.length) {
    throw new Error("no arena custom presets could be derived from meta_teams.json");
  }

  const meta = {
    schema: "arena-custom-presets.v2",
    source: "data/arena/meta_teams.json",
    generatedBy: "tools/derive-arena-custom-presets.js",
    presetCount: presets.length,
    skippedCount: skipped.length,
    skippedReason: `red side exceeds ${MAX_SIDE_COUNT} units or has no valid members`,
    blueBench: {
      benchId: "thief-lv30x4",
      roster: BENCH_ROSTER.map((entry) => ({
        type: `兵种${entry.id}`,
        level: entry.level,
        count: entry.count,
      })),
    },
  };

  return [
    "// AUTO-GENERATED by tools/derive-arena-custom-presets.js — 请勿手改，改 data/arena/meta_teams.json 后重跑。",
    "// 定制死亡竞赛待标定组合：蓝方为 thief-lv30x4 对照阵容，红方为关卡拆解元战队。",
    "(function() {",
    "    'use strict';",
    "    if (typeof window === \"undefined\") return;",
    `    window.ArenaCustomPresetsMeta = ${JSON.stringify(meta)};`,
    `    window.ArenaCustomPresets = ${JSON.stringify(presets)};`,
    "})();",
    "",
  ].join("\n");
}

function main() {
  const expected = buildModule();
  const check = process.argv.indexOf("--check") >= 0;
  const current = fs.existsSync(OUTPUT_PATH) ? fs.readFileSync(OUTPUT_PATH, "utf8") : "";

  if (check) {
    if (current !== expected) {
      throw new Error("launcher/web/modules/arena-custom-presets.js is stale; run node tools/derive-arena-custom-presets.js");
    }
    console.log("[derive-arena-custom-presets] up-to-date");
    return;
  }

  fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
  if (current !== expected) {
    fs.writeFileSync(OUTPUT_PATH, expected, "utf8");
    console.log("[derive-arena-custom-presets] wrote " + path.relative(ROOT, OUTPUT_PATH));
  } else {
    console.log("[derive-arena-custom-presets] unchanged");
  }
}

try {
  main();
} catch (error) {
  console.error(error.message);
  process.exit(1);
}
