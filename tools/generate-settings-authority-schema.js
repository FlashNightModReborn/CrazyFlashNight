'use strict';
const fs=require('fs');
const path=require('path');
const root=path.resolve(__dirname,'..');
const schema=JSON.parse(fs.readFileSync(path.join(root,'launcher/contracts/settings-authority.v2.json'),'utf8'));
if(schema.schema!=='cf7.settings-authority.v2'||schema.settings.length!==14||schema.keys.length!==36
  ||new Set(schema.settings).size!==14||new Set(schema.keys).size!==36
  ||schema.booleanIndexes.some(x=>!Number.isInteger(x)||x<0||x>13))throw new Error('Invalid fixed settings schema');
const strings=items=>items.map(JSON.stringify).join(', ');
const csharp=`// Generated by tools/generate-settings-authority-schema.js; edit the contract JSON.\nnamespace CF7Launcher.Save\n{\n    internal static class SettingsCanonicalSchema\n    {\n        internal static readonly string[] Settings = { ${strings(schema.settings)} };\n        internal static readonly string[] KeyIds = { ${strings(schema.keys)} };\n        internal static readonly int[] BooleanIndexes = { ${schema.booleanIndexes.join(', ')} };\n        internal static readonly string[] PlayModes = { ${strings(schema.playModes)} };\n    }\n}\n`;
const as2=`// Generated by tools/generate-settings-authority-schema.js; edit the contract JSON.\nclass org.flashNight.neur.Server.SettingsCanonicalSchema {\n    public static var SETTING_IDS:Array = [${strings(schema.settings)}];\n    public static var KEY_IDS:Array = [${strings(schema.keys)}];\n    public static var BOOLEAN_INDEXES:Array = [${schema.booleanIndexes.join(', ')}];\n    public static var PLAY_MODES:Array = [${strings(schema.playModes)}];\n}\n`;
const outputs=[['launcher/src/Save/SettingsCanonical.Schema.cs',Buffer.from(csharp)],
  ['scripts/类定义/org/flashNight/neur/Server/SettingsCanonicalSchema.as',Buffer.concat([Buffer.from([239,187,191]),Buffer.from(as2)])]];
for(const [relative,bytes] of outputs){
  const file=path.join(root,relative);
  if(process.argv.includes('--check')){
    if(!fs.existsSync(file)||!fs.readFileSync(file).equals(bytes))throw new Error('Stale generated schema: '+relative);
  }else {
    if(relative.endsWith('.as')&&!fs.existsSync(file))fs.copyFileSync(path.join(root,'scripts/类定义/org/flashNight/neur/Server/SaveManager.as'),file);
    fs.writeFileSync(file,bytes);
  }
}
console.log('settings authority schema: 14 settings, 36 keys, C#/AS2 agree');
