#!/usr/bin/env node
'use strict';
const fs=require('fs'),path=require('path'),crypto=require('crypto');
const root=path.resolve(__dirname,'..');
const names={Andy:'remake-andy.png',TheGirl:'remake-thegirl.png',Blue:'remake-blue.png',ShopGirl:'remake-shopgirl.png',
    Boy:'remake-boy.png',Pig:'remake-pig.png',King:'remake-king.png','过场1':'fanmade-01.png','过场2':'fanmade-02.png',
    '武器':'official-weapons.jpg','7代主角1':'official-hero1.jpg','7代主角2':'official-hero2.jpg',
    '黑铁众':'official-ironcrew.jpg','诺亚方舟1':'official-ark.jpg'};
const source=path.join(root,'flashswf/UI/加载背景');
const xml=fs.readFileSync(path.join(source,'LIBRARY/加载背景 1024&#042576.xml'),'utf8');
function layer(name){const match=xml.match(new RegExp('<DOMLayer name="'+name+'"[\\s\\S]*?</DOMLayer>'));if(!match)throw Error('missing source layer '+name);return match[0];}
const labels=Array.from(layer('label').matchAll(/<DOMFrame index="(\d+)"[^>]* name="([^"]+)"/g));
const pictures=new Map(Array.from(layer('Layer 2').matchAll(/<DOMFrame index="(\d+)"[\s\S]*?<DOMBitmapInstance libraryItemName="([^"]+)"[\s\S]*?<\/DOMFrame>/g),m=>[m[1],m[2]]));
const available=JSON.parse(fs.readFileSync(path.join(root,'launcher/web/assets/bg/manifest.json'),'utf8')).backgrounds;
const sha=p=>crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
const assets={},audit=[];
for(const [,index,id] of labels){
    const file=names[id],relative=pictures.get(index);
    if(!file || !relative || !available.includes(file))throw Error('unmapped loading background '+id);
    const original=path.join(source,'LIBRARY',relative),target=path.join(root,'launcher/web/assets/bg',file);
    if(sha(original)!==sha(target))throw Error('background bytes differ: '+id);
    assets[id]='assets/bg/'+file;
    audit.push({id,source:path.relative(root,original).replaceAll('\\','/'),asset:assets[id],sha256:sha(target)});
}
if(labels.length!==Object.keys(names).length)throw Error('source loading labels changed; review mapping');
const as=fs.readFileSync(path.join(root,'scripts/类定义/org/flashNight/arki/ui/SceneTransitionService.as'),'utf8');
for(const id of Object.keys(assets))if(!as.includes('case "'+id+'"'))throw Error('AS2 image allowlist missing '+id);
const outputs={
    'launcher/web/generated/scene-transition-catalog.js':'// Generated by tools/generate-scene-transition-catalog.js; original XFL pixels, no brightness filter.\nvar SceneTransitionCatalog = Object.freeze('+JSON.stringify(assets,null,2)+');\n',
    'launcher/src/Tasks/SceneTransitionCatalog.Generated.cs':'// Generated by tools/generate-scene-transition-catalog.js.\nusing System.Collections.Generic;\nnamespace CF7Launcher.Tasks {\n    internal static class SceneTransitionCatalog {\n        internal static readonly IReadOnlyDictionary<string,string> Assets = new Dictionary<string,string> {\n'+Object.entries(assets).map(([id,p])=>'            ["'+id+'"] = "'+p+'",').join('\n')+'\n        };\n    }\n}\n',
    'launcher/data/scene-transition/catalog.manifest.json':JSON.stringify({version:1,count:audit.length,images:audit},null,2)+'\n'
};
for(const [name,text] of Object.entries(outputs)){
    const p=path.join(root,name);
    if(process.argv.includes('--check')){if(!fs.existsSync(p)||fs.readFileSync(p,'utf8').replace(/\r\n/g,'\n')!==text)throw Error('stale generated file '+name);}
    else{fs.mkdirSync(path.dirname(p),{recursive:true});fs.writeFileSync(p,text);}
}
console.log('Scene transition catalog: '+audit.length+' original-byte backgrounds; '+(process.argv.includes('--check')?'checked':'generated'));
